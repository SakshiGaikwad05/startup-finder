/** Square with the startup's first letter; colour is stable per name so lists are easier to scan. */
const AVATAR_TONES = [
  "bg-brand-100 text-brand-700",
  "bg-emerald-100 text-emerald-800",
  "bg-amber-100 text-amber-800",
  "bg-rose-100 text-rose-700",
  "bg-sky-100 text-sky-700",
  "bg-violet-100 text-violet-700",
];

export function Avatar({ name, size = "md" }: { name: string; size?: "sm" | "md" | "lg" }) {
  let h = 0;
  for (const c of name) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  const dims = size === "lg" ? "h-14 w-14 text-2xl rounded-2xl" : size === "sm" ? "h-8 w-8 text-sm rounded-lg" : "h-11 w-11 text-lg rounded-xl";
  return (
    <div className={`flex shrink-0 items-center justify-center font-display font-semibold ${dims} ${AVATAR_TONES[h % AVATAR_TONES.length]}`} aria-hidden="true">
      {name.trim().slice(0, 1).toUpperCase() || "?"}
    </div>
  );
}
